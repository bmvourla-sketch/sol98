// Security headers, incl. a Content-Security-Policy. Ad blocks/imageSrc are
// deliberately wide open: users paste arbitrary http(s) image/banner URLs
// (see lib/pixel-types.ts's isSafeImageUrl) as a core feature of the pixel
// board, so a strict image allowlist would break normal use. connect-src is
// similarly wide to allow whichever Solana RPC + Supabase endpoints are
// configured per environment. Everything else (script/style/object/frame)
// is locked down.
const CSP = [
  "default-src 'self'",
  "script-src 'self' 'unsafe-inline'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob: https: http:",
  "font-src 'self' data:",
  "connect-src 'self' https: wss: http:",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
].join("; ");

/** @type {import('next').NextConfig} */
const nextConfig = {
  poweredByHeader: false,
  reactStrictMode: true,
  async headers() {
    return [
      {
        source: "/:path*",
        headers: [
          { key: "Content-Security-Policy", value: CSP },
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
          { key: "X-Frame-Options", value: "DENY" },
          { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
        ],
      },
    ];
  },
};

export default nextConfig;
